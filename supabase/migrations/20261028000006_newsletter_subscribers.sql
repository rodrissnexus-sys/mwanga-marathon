-- Footer newsletter sign-ups. Written by the server (secret key) only; staff
-- can read them in the dashboard and export the list.
create table public.newsletter_subscribers (
  id bigint generated by default as identity primary key,
  email text not null check (char_length(email) <= 255),
  locale public.app_locale not null default 'en',
  created_at timestamptz not null default now()
);

create unique index newsletter_subscribers_email_idx on public.newsletter_subscribers (lower(email));

alter table public.newsletter_subscribers enable row level security;

create policy "Staff can read subscribers" on public.newsletter_subscribers
  for select to authenticated using ((select private.is_staff()));
create policy "Admins can remove subscribers" on public.newsletter_subscribers
  for delete to authenticated using ((select private.is_admin()));

revoke all on public.newsletter_subscribers from anon;
revoke insert, update, truncate on public.newsletter_subscribers from authenticated;
