-- Payment confirmation details and a permanent payment log.
--
-- Staff (admins and moderators) confirm a payment after checking the
-- mobile-money / bank SMS or statement. They now record how it was paid, the
-- transaction reference and the amount received, and every status change is
-- written to payment_events (who, when, what) by a trigger, so the log can't
-- be skipped or edited from the dashboard.

create type public.payment_method as enum ('mobile_money', 'bank_transfer', 'cash', 'other');

alter table public.registrations
  add column payment_method public.payment_method,
  add column payment_reference text check (char_length(payment_reference) <= 100),
  add column payment_amount numeric(12, 2) check (payment_amount >= 0),
  add column payment_currency text check (payment_currency in ('TZS', 'USD'));

comment on column public.registrations.payment_reference is 'Mobile-money transaction ID or bank reference the payment was matched with.';
comment on column public.registrations.payment_amount is 'Amount actually received (may differ from the race fee).';

-- finds a reference already used on another registration
create index registrations_payment_reference_idx on public.registrations (lower(payment_reference))
  where payment_reference is not null;

create table public.payment_events (
  id bigint generated by default as identity primary key,
  registration_id bigint not null references public.registrations (id) on delete cascade,
  status public.payment_status not null,
  previous_status public.payment_status,
  method public.payment_method,
  reference text,
  amount numeric(12, 2),
  currency text,
  notes text,
  actor_id uuid references public.profiles (id) on delete set null,
  actor_name text,
  created_at timestamptz not null default now()
);

comment on table public.payment_events is 'Every payment status change, written by a trigger on registrations.';

create index payment_events_registration_id_idx on public.payment_events (registration_id, created_at desc);
create index payment_events_actor_id_idx on public.payment_events (actor_id);

alter table public.payment_events enable row level security;

-- read-only for staff; rows are only ever added by the trigger below
create policy "Staff can read payment events" on public.payment_events
  for select to authenticated using ((select private.is_staff()));

create function private.log_payment_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.payment_status is distinct from old.payment_status then
    insert into public.payment_events
      (registration_id, status, previous_status, method, reference, amount, currency, notes, actor_id, actor_name)
    values (
      new.id, new.payment_status, old.payment_status,
      new.payment_method, new.payment_reference, new.payment_amount, new.payment_currency,
      new.payment_notes,
      auth.uid(),
      coalesce((select name from public.profiles where id = auth.uid()), new.payment_confirmed_by_name)
    );
  end if;
  return new;
end;
$$;

create trigger registrations_log_payment_change after update of payment_status on public.registrations
  for each row execute function private.log_payment_change();

-- Undoing a confirmed payment is for admins only. (No auth.uid() means the
-- server's secret key or a migration, which is allowed.)
create function private.guard_confirmed_payment()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.payment_status = 'confirmed' and new.payment_status is distinct from old.payment_status
     and auth.uid() is not null and not private.is_admin() then
    raise exception 'Only an admin can change a confirmed payment' using errcode = '42501';
  end if;
  return new;
end;
$$;

create trigger registrations_guard_confirmed_payment before update of payment_status on public.registrations
  for each row execute function private.guard_confirmed_payment();
