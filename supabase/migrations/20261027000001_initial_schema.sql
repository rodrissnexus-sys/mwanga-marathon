-- Role of the signed-in user (null for visitors). SECURITY DEFINER so RLS
-- policies can call it without recursing into the profiles policies.
create function private.user_role()
returns public.app_role
language sql
stable
security definer
set search_path = ''
as $$
  select role from public.profiles where id = (select auth.uid());
$$;

create function private.is_staff()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(private.user_role() in ('admin', 'moderator'), false);
$$;

create function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(private.user_role() = 'admin', false);
$$;

grant usage on schema private to anon, authenticated;
grant execute on function private.user_role(), private.is_staff(), private.is_admin()
  to anon, authenticated;

-- Staff accounts are created from the dashboard with the Auth admin API
-- (server side, secret key), passing role in app_metadata — which users
-- cannot edit themselves. This trigger turns that into a profile row.
-- Accounts without a role (e.g. someone using public sign-up) get no
-- profile, so they have no staff access at all.
create function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.raw_app_meta_data ->> 'role' in ('admin', 'moderator') then
    insert into public.profiles (id, name, email, role)
    values (
      new.id,
      coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), split_part(new.email, '@', 1)),
      new.email,
      (new.raw_app_meta_data ->> 'role')::public.app_role
    );
  end if;
  return new;
end;
$$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function private.handle_new_user();

