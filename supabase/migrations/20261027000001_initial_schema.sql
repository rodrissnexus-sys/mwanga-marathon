-- Public content: visitors see active rows, staff see all, admins edit.
do $$
declare
  t text;
begin
  foreach t in array array[
    'events', 'shirt_sizes', 'collection_venues', 'countries', 'genders',
    'event_types', 'event_features', 'schedule_days', 'schedule_events',
    'marathon_banners'
  ] loop
    execute format(
      'create policy "Anyone can read active rows; staff read all" on public.%I
         for select to anon, authenticated
         using (is_active or (select private.is_staff()))', t);
    execute format(
      'create policy "Admins can insert" on public.%I
         for insert to authenticated
         with check ((select private.is_admin()))', t);
    execute format(
      'create policy "Admins can update" on public.%I
         for update to authenticated
         using ((select private.is_admin()))
         with check ((select private.is_admin()))', t);
    execute format(
      'create policy "Admins can delete" on public.%I
         for delete to authenticated
         using ((select private.is_admin()))', t);
  end loop;
end;
$$;

