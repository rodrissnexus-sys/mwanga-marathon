-- MWAFEM initial schema
--
-- Replaces the two Laravel/MySQL databases (English + Swahili) with one
-- database. Text shown to visitors has an English column (required) and a
-- Swahili column (optional; the site falls back to English when it is empty).
--
-- Security model
--   * Row Level Security is enabled on every table.
--   * Visitors (anon) can only READ active public content.
--   * Staff log in with Supabase Auth; their role lives in public.profiles.
--     moderator: read everything, manage registrations/payments/messages.
--     admin:     everything a moderator can, plus content and users.
--   * Public form submissions (registrations, contact messages) are inserted
--     by the Next.js server with the secret key after validation and rate
--     limiting — never directly from the browser.

create extension if not exists pg_trgm with schema extensions;

