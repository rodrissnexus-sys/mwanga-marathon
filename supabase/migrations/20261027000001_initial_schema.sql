-- ---------------------------------------------------------------------------
-- Rate limiting for public forms (server-only)
-- ---------------------------------------------------------------------------

create table public.rate_limits (
  key text not null,
  window_start timestamptz not null,
  hits integer not null default 0,
  primary key (key, window_start)
);

comment on table public.rate_limits is 'Counters for form rate limiting. Only the server (secret key) uses it.';

-- Counts one hit for `p_key` in the current window and says whether it is
-- still within `p_max`. Old windows are cleaned up opportunistically.
create function public.hit_rate_limit(p_key text, p_max integer, p_window_seconds integer)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_window timestamptz := to_timestamp(
    floor(extract(epoch from now()) / p_window_seconds) * p_window_seconds
  );
  v_hits integer;
begin
  insert into public.rate_limits as rl (key, window_start, hits)
  values (p_key, v_window, 1)
  on conflict (key, window_start) do update set hits = rl.hits + 1
  returning hits into v_hits;

  delete from public.rate_limits
  where window_start < now() - make_interval(secs => p_window_seconds * 2);

  return v_hits <= p_max;
end;
$$;

revoke execute on function public.hit_rate_limit(text, integer, integer) from public, anon, authenticated;
grant execute on function public.hit_rate_limit(text, integer, integer) to service_role;

